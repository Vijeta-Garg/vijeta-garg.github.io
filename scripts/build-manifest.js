#!/usr/bin/env node
/* =====================================================================
   build-manifest.js
   Scans the content/ folder and writes content/manifest.js, the list of
   every photo, video, document, slide deck and blog post on the site.

   GitHub runs this automatically on every push (.github/workflows/deploy.yml).
   To preview new files on your own computer, run:   node scripts/build-manifest.js
   No packages to install: it only uses Node's built-in modules.
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CONTENT = path.join(ROOT, 'content');

const KINDS = {
  images: ['jpg', 'jpeg', 'png', 'gif', 'webp', 'avif', 'svg'],
  videos: ['mp4', 'webm', 'mov', 'm4v', 'ogg'],
  files: null,                                   // anything
  slides: ['ppt', 'pptx', 'pdf', 'key', 'odp']
};
const IGNORE = /^(\.|_|readme\.md$|thumbs\.db$|desktop\.ini$)/i;

const toUrl = p => path.relative(ROOT, p).split(path.sep).map(encodeURIComponent).join('/');
const natural = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
const isDir = p => { try { return fs.statSync(p).isDirectory(); } catch (e) { return false; } };
const listDir = p => (isDir(p) ? fs.readdirSync(p) : []);

function filesIn(dir, exts) {
  return listDir(dir)
    .filter(f => !IGNORE.test(f) && !isDir(path.join(dir, f)))
    .filter(f => !exts || exts.includes(path.extname(f).slice(1).toLowerCase()))
    .sort(natural)
    .map(f => toUrl(path.join(dir, f)));
}

/* ---------- media for research / projects / community ---------- */
const media = {};
for (const section of ['research', 'projects', 'community']) {
  const sectionDir = path.join(CONTENT, section);
  for (const id of listDir(sectionDir).sort(natural)) {
    const itemDir = path.join(sectionDir, id);
    if (!isDir(itemDir) || IGNORE.test(id)) continue;
    const entry = {};
    for (const [kind, exts] of Object.entries(KINDS)) {
      const found = filesIn(path.join(itemDir, kind), exts);
      if (found.length) entry[kind] = found;
    }
    if (Object.keys(entry).length) media[`${section}/${id}`] = entry;
  }
}

/* ---------- blog posts (content/blog/*.md with a --- header ---) ---------- */
function parsePost(file) {
  const raw = fs.readFileSync(file, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
  const meta = {};
  let body = raw;
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (m) {
    body = m[2];
    for (const line of m[1].split('\n')) {
      const kv = line.match(/^\s*([A-Za-z_]+)\s*:\s*(.*)$/);
      if (kv) meta[kv[1].toLowerCase()] = kv[2].trim().replace(/^["']|["']$/g, '');
    }
  }
  const slug = path.basename(file, '.md').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return {
    slug,
    title: meta.title || slug,
    date: meta.date || '',
    summary: meta.summary || '',
    tags: meta.tags ? meta.tags.split(',').map(t => t.trim()).filter(Boolean) : [],
    cover: meta.cover || '',
    emoji: meta.emoji || '',
    body
  };
}
const blogDir = path.join(CONTENT, 'blog');
const posts = listDir(blogDir)
  .filter(f => f.toLowerCase().endsWith('.md') && !IGNORE.test(f))
  .map(f => parsePost(path.join(blogDir, f)))
  .sort((a, b) => (b.date || '').localeCompare(a.date || '') || natural(a.title, b.title));

/* ---------- write ---------- */
const out =
`/* AUTO-GENERATED by scripts/build-manifest.js. Don't edit by hand.
   Lists the files found in content/. Rebuilt automatically on every push. */
window.MEDIA = ${JSON.stringify(media, null, 2)};
window.BLOG_POSTS = ${JSON.stringify(posts, null, 2)};
`;
fs.writeFileSync(path.join(CONTENT, 'manifest.js'), out);

const counts = Object.values(media).reduce((n, e) => n + Object.values(e).reduce((k, l) => k + l.length, 0), 0);
console.log(`manifest.js written: ${counts} media file(s) in ${Object.keys(media).length} folder(s), ${posts.length} blog post(s).`);
